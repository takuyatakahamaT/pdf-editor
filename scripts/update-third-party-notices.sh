#!/bin/zsh
set -euo pipefail

APP_DIR="${0:A:h:h}"
GO_COMMAND="$(command -v go || true)"
if [[ -z "$GO_COMMAND" ]]; then
    echo "Go 1.26以降が必要です。" >&2
    exit 1
fi

WORK_DIR="$(/usr/bin/mktemp -d "${TMPDIR:-/tmp}/pdf-editor-notices.XXXXXXXX")"
trap '/bin/rm -rf "$WORK_DIR"' EXIT
GO_LICENSES_BIN="$WORK_DIR/go-licenses"
HELPER_LICENSES="$WORK_DIR/helper"
LINK_REMAP_LICENSES="$WORK_DIR/link-remap"
PDFCPU_LICENSES="$WORK_DIR/pdfcpu-cli"

GOBIN="$WORK_DIR" "$GO_COMMAND" install github.com/google/go-licenses/v2@v2.0.1
(
    cd "$APP_DIR/Tools/pdf-compress"
    "$GO_LICENSES_BIN" save . --save_path "$HELPER_LICENSES" --force --ignore pdf-editor-compress
)
(
    cd "$APP_DIR/Tools/pdf-link-remap"
    "$GO_LICENSES_BIN" save . --save_path "$LINK_REMAP_LICENSES" --force --ignore pdf-editor-pdf-link-remap
)

/bin/mkdir -p "$WORK_DIR/pdfcpu-cli-module"
cat > "$WORK_DIR/pdfcpu-cli-module/go.mod" <<'EOF'
module pdf-editor-pdfcpu-cli-notices

go 1.26.0

require github.com/pdfcpu/pdfcpu v0.16.2
EOF
(
    cd "$WORK_DIR/pdfcpu-cli-module"
    "$GO_COMMAND" get github.com/pdfcpu/pdfcpu/cmd/pdfcpu@v0.16.2
    "$GO_LICENSES_BIN" save github.com/pdfcpu/pdfcpu/cmd/pdfcpu \
        --save_path "$PDFCPU_LICENSES" --force
)

NOTICES="$APP_DIR/Resources/ThirdParty/THIRD-PARTY-NOTICES.txt"
PDFCPU_LICENSE="$APP_DIR/Resources/ThirdParty/pdfcpu-LICENSE.txt"
GO_ROOT="$("$GO_COMMAND" env GOROOT)"
GO_LICENSE_FILE="$GO_ROOT/LICENSE"
if [[ ! -f "$GO_LICENSE_FILE" ]]; then
    GO_LICENSE_FILE="${GO_ROOT:h}/LICENSE"
fi
if [[ ! -f "$GO_LICENSE_FILE" ]]; then
    echo "Go toolchainのLICENSEファイルが見つかりません。" >&2
    exit 1
fi
/bin/mkdir -p "${NOTICES:h}"

{
    cat <<'EOF'
Third-party software notices for NIHO PDF editor
================================================

The app bundles the Go-based pdfcpu command line tool and uses pdfcpu from the
PDF compression and internal-link helpers. The following files contain the license texts and
notices detected for the bundled Go dependency graph. The Go standard library
license is included at the end. Each component remains under its own license.

Generated by scripts/update-third-party-notices.sh using google/go-licenses
v2.0.1. The scan includes Tools/pdf-compress, Tools/pdf-link-remap, and github.com/pdfcpu/pdfcpu/cmd/pdfcpu.

EOF
    typeset -A seen
    for license_root in "$HELPER_LICENSES" "$LINK_REMAP_LICENSES" "$PDFCPU_LICENSES"; do
        while IFS= read -r license_file; do
            relative_path="${license_file#"$license_root"/}"
            if [[ -n "${seen[$relative_path]-}" ]]; then
                continue
            fi
            seen[$relative_path]=1
            print "\n\n================================================================\n$relative_path\n================================================================\n"
            cat "$license_file"
        done < <(/usr/bin/find "$license_root" -type f -print | /usr/bin/sort)
    done

    print "\n\n================================================================\nGo toolchain license\n================================================================\n"
    cat "$GO_LICENSE_FILE"
} > "$NOTICES"

/bin/cp "$PDFCPU_LICENSES/github.com/pdfcpu/pdfcpu/LICENSE.txt" "$PDFCPU_LICENSE"
echo "依存ライセンスを更新しました: $NOTICES"
